/**
 * The BitKnit2 decoder, against real Resurrected section payloads plus
 * streams built here.
 *
 * `tools/verify-bitknit2.ts` decodes the full game sections (megabytes of
 * output); these cases pin the reading itself — the quantum framing, the raw
 * quantum, the bounds checks — so a change to any of it fails here rather than
 * only in a run that needs the game data. The fixtures are the smallest real
 * streams that exercise each path: two from `blend_sphere`'s sections and the
 * file's two pointer-fixup frames, copied byte for byte from the retail data.
 * Decoded hashes are MD5s of the exact expected output; nothing here is a
 * snapshot of decoder output generated by this code.
 */

// @vitest-environment node
// The fixtures are read from disk with `new URL(..., import.meta.url)`, and
// under the jsdom environment vitest rewrites `import.meta.url` to the dev
// server's `http://localhost:3000/...`, which `readFileSync` cannot open.
// The suite is plain Node file I/O, so it asks for the node environment.
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { md5Hex } from '@rasenjs/assets'
import { BITKNIT2_MAGIC, decodeBitknit2, isBitknit2 } from '@rasenjs/assets'

/** Load one binary fixture. */
function fixture(name: string): Uint8Array {
  return new Uint8Array(readFileSync(new URL(`./fixtures/${name}`, import.meta.url)))
}

const mainFixture = fixture('bitknit2-blend-sphere-main.bin')
const discardableFixture = fixture('bitknit2-blend-sphere-discardable.bin')
const fixupFixture = fixture('bitknit2-blend-sphere-fixup.bin')
const tinyFixupFixture = fixture('bitknit2-blend-sphere-fixup-tiny.bin')

/**
 * A raw quantum stream: magic, a NUL word, then plain bytes. This is the
 * "stored" form of the format and needs no encoder to build.
 */
function rawStream(payload: Uint8Array): Uint8Array {
  const out = new Uint8Array(4 + payload.length)
  out[0] = 0xb1
  out[1] = 0x75
  out.set(payload, 4)
  return out
}

/** Deterministic noise, standing in for stored section bytes. */
function noise(length: number, seed = 1): Uint8Array {
  const out = new Uint8Array(length)
  let state = seed >>> 0
  for (let i = 0; i < length; i++) {
    state = (state * 1664525 + 1013904223) >>> 0
    out[i] = (state >>> 24) & 0xff
  }
  return out
}

describe('isBitknit2', () => {
  it('accepts the little-endian magic word (the bytes b1 75)', () => {
    expect(BITKNIT2_MAGIC).toBe(0x75b1)
    expect(isBitknit2(Uint8Array.from([0xb1, 0x75]))).toBe(true)
    expect(isBitknit2(mainFixture)).toBe(true)
  })

  it('rejects short inputs and other magic', () => {
    expect(isBitknit2(new Uint8Array(0))).toBe(false)
    expect(isBitknit2(Uint8Array.from([0xb1]))).toBe(false)
    expect(isBitknit2(Uint8Array.from([0x75, 0xb1]))).toBe(false)
    expect(isBitknit2(Uint8Array.from([0xb2, 0x75]))).toBe(false)
  })
})

describe('malformed input', () => {
  it('rejects bad magic with a descriptive error', () => {
    expect(() => decodeBitknit2(Uint8Array.from([0xb2, 0x75, 0, 0]), 1)).toThrow(/bad magic/)
  })

  it('rejects invalid destination lengths', () => {
    expect(() => decodeBitknit2(tinyFixupFixture, -1)).toThrow(/invalid destination length/)
    expect(() => decodeBitknit2(tinyFixupFixture, 1.5)).toThrow(/invalid destination length/)
  })

  it('decodes an empty output from any stream with valid magic', () => {
    expect(decodeBitknit2(Uint8Array.from([0xb1, 0x75]), 0)).toEqual(new Uint8Array(0))
  })

  it('rejects a stream truncated to nothing useful', () => {
    expect(() => decodeBitknit2(Uint8Array.from([0xb1, 0x75]), 1)).toThrow(/truncated/)
    expect(() => decodeBitknit2(new Uint8Array(0), 1)).toThrow(/bad magic/)
  })

  it('rejects a truncated coded stream', () => {
    expect(() => decodeBitknit2(discardableFixture.subarray(0, 200), 17116)).toThrow(
      /unexpected end of stream/,
    )
  })

  it('rejects a corrupted coded stream instead of returning garbage', () => {
    const corrupted = discardableFixture.slice()
    corrupted[10] ^= 0xff
    expect(() => decodeBitknit2(corrupted, 17116)).toThrow(/BitKnit2:/)
  })
})

describe('raw quanta', () => {
  it('copies stored bytes verbatim', () => {
    const payload = noise(300)
    expect(decodeBitknit2(rawStream(payload), 300)).toEqual(payload)
  })

  it('stops at the requested length and reports truncation past it', () => {
    const payload = noise(300)
    expect(decodeBitknit2(rawStream(payload), 7)).toEqual(payload.subarray(0, 7))
    expect(() => decodeBitknit2(rawStream(payload), 301)).toThrow(/truncated/)
  })

  it('splits output at 64 KiB quantum boundaries', () => {
    // A raw stream carries one NUL word at the start of *each* quantum, so a
    // payload that crosses 64 KiB is framed in two pieces.
    const head = noise(65536, 2)
    const tail = noise(4464, 3)
    const stream = new Uint8Array(4 + 2 + head.length + 2 + tail.length)
    stream[0] = 0xb1
    stream[1] = 0x75
    stream.set(head, 4)
    stream.set(tail, 6 + head.length)
    const expected = new Uint8Array(head.length + tail.length)
    expected.set(head)
    expected.set(tail, head.length)
    expect(decodeBitknit2(stream, 70000)).toEqual(expected)
    // The first quantum ends at 65536 even though the bytes are contiguous.
    expect(decodeBitknit2(stream, 65536)).toEqual(head)
    expect(decodeBitknit2(stream, 65537)).toEqual(expected.subarray(0, 65537))
  })
})

describe('real section payloads (blend_sphere)', () => {
  it('decodes the raw pointer-fixup frame to its 16 stored bytes', () => {
    // A stored (raw-quantum) stream: the frame decodes to any length up to its
    // 16 bytes, which is exactly the raw quantum rule, and the bytes come back
    // untouched.
    const expected = Uint8Array.from([
      0xb7, 0x01, 0x00, 0x00, 0xd4, 0x35, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x44, 0x24, 0x00,
      0x00,
    ])
    expect(tinyFixupFixture.subarray(4)).toEqual(expected)
    expect(decodeBitknit2(tinyFixupFixture, 16)).toEqual(expected)
    expect(decodeBitknit2(tinyFixupFixture, 5)).toEqual(expected.subarray(0, 5))
    expect(() => decodeBitknit2(tinyFixupFixture, 17)).toThrow(/truncated/)
    expect(md5Hex(decodeBitknit2(tinyFixupFixture, 16))).toBe('61f172c4b03bf482c1d9898de4900a39')
  })

  it('decodes the discardable section to exactly 17116 bytes', () => {
    const out = decodeBitknit2(discardableFixture, 17116)
    expect(out.length).toBe(17116)
    expect(md5Hex(out)).toBe('461a0b4b0e81e92f7043542856bd0633')
  })

  it('ignores an odd trailing source byte, as the word-based stream does', () => {
    // One byte short of the real frame: still the same stream in 16-bit words.
    expect(md5Hex(decodeBitknit2(discardableFixture.subarray(0, 547), 17116))).toBe(
      '461a0b4b0e81e92f7043542856bd0633',
    )
  })

  it('rejects wrong output lengths', () => {
    expect(() => decodeBitknit2(discardableFixture, 17115)).toThrow(/overruns the output/)
    expect(() => decodeBitknit2(discardableFixture, 17117)).toThrow(/rANS stream corrupted/)
  })

  it('decodes the main section and its Granny type tree', () => {
    const out = decodeBitknit2(mainFixture, 25984)
    expect(out.length).toBe(25984)
    expect(md5Hex(out)).toBe('639e6466f3a985d53838a05446b225b0')
    // The self-describing type tree: printable ASCII survives the entropy
    // coding unchanged.
    const text = Buffer.from(out).toString('latin1')
    for (const name of ['Mesh', 'VertexData', 'Skeleton', 'Material', 'Bone']) {
      expect(text).toContain(name)
    }
  })

  it('decodes the pointer-fixup table to 251 x 12-byte triples', () => {
    const out = decodeBitknit2(fixupFixture, 3012)
    expect(out.length).toBe(251 * 12)
    expect(md5Hex(out)).toBe('27f8124c53e31a8937683135f8594eca')
    const view = new DataView(out.buffer, out.byteOffset, out.byteLength)
    expect([0, 4, 8].map((at) => view.getUint32(at, true))).toEqual([0, 0, 148])
    const last = (251 - 1) * 12
    expect([0, 4, 8].map((at) => view.getUint32(last + at, true))).toEqual([5376, 0, 5028])
    for (let entry = 0; entry < 251; entry++) {
      // (srcOffset, dstSection, dstOffset) triples: section indices are small
      // and offsets stay inside the decompressed sections.
      expect(view.getUint32(entry * 12 + 4, true)).toBeLessThan(16)
      expect(view.getUint32(entry * 12 + 8, true)).toBeLessThan(1 << 20)
    }
  })
})
